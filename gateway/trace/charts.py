"""Server-rendered SVG charts, and the parser that feeds them.

The numbers come from ``results/table.md`` -- the file ``scripts/experiment.py``
writes -- and from nowhere else. That is the same rule the replay view follows
with traces: **the page is a view of a product, not a second producer of it.**
Hand-typing 182/65 into the templates would have been the shortest path and the
one thing guaranteed to go stale quietly.

Why SVG strings instead of a charting library: the replay page has to work as a
single file with no network, and the index has to render the same bytes twice.
A canvas chart needs a runtime; a CDN chart needs a connection; a chart drawn by
JavaScript would be a second implementation of the scale, and the two would
disagree at the axis labels where nobody looks.

Parsing markdown is not elegant. It is, however, exactly as brittle as the
product is stable: the table is generated by our own script, its header is
matched by name rather than by column index, and anything unrecognised degrades
to "no metrics" instead of to a wrong chart. A wrong chart is worse than a
missing one -- it would still look like evidence.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

__all__ = [
    "TaskRow",
    "Report",
    "load_report",
    "chart_calls",
    "chart_task_steps",
    "chart_accuracy",
]


@dataclass(frozen=True)
class TaskRow:
    task: str
    kind: str
    optimal: int
    baseline: int
    governed: int
    rule: str


@dataclass(frozen=True)
class Report:
    baseline_calls: int
    governed_calls: int
    saved_pct: Optional[float]
    right_baseline: str
    right_governed: str
    early_governed: str
    late_baseline: str
    acc_baseline: Optional[float]
    acc_governed: Optional[float]
    tasks: Tuple[TaskRow, ...]

    @property
    def total_tasks(self) -> int:
        return len(self.tasks)


# -- parsing --------------------------------------------------------------

_CELL = re.compile(r"^-{2,}$")


def _cells(line: str) -> List[str]:
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def _first_int(text: str) -> Optional[int]:
    found = re.search(r"-?\d+", text)
    return int(found.group()) if found else None


def _first_float(text: str) -> Optional[float]:
    found = re.search(r"-?\d+(?:\.\d+)?", text)
    return float(found.group()) if found else None


def _tables(text: str) -> List[Tuple[List[str], List[List[str]]]]:
    """Every markdown table in ``text`` as ``(header, rows)``.

    Header-driven rather than position-driven: the per-task table gained a
    column between D11 and D12, and a parser that counted columns would have
    kept producing a chart with the rule names in the steps column.
    """
    tables: List[Tuple[List[str], List[List[str]]]] = []
    header: Optional[List[str]] = None
    rows: List[List[str]] = []

    def flush() -> None:
        nonlocal header, rows
        if header is not None:
            tables.append((header, rows))
        header, rows = None, []

    for line in text.splitlines():
        stripped = line.strip()
        if not stripped.startswith("|"):
            flush()
            continue
        cells = _cells(stripped)
        if header is None:
            header = cells
            continue
        if all(_CELL.match(cell) for cell in cells if cell):
            continue
        rows.append(cells)
    flush()
    return tables


def _column(header: Sequence[str], name: str) -> Optional[int]:
    for index, cell in enumerate(header):
        if cell == name:
            return index
    return None


def load_report(path: Path) -> Optional[Report]:
    """Read ``results/table.md``. ``None`` when the file is absent or unusable.

    The page then says "no metrics yet, run scripts/experiment.py" -- an empty
    state, not an error page and not a chart of zeros. Zeros would be a
    measurement claim.
    """
    path = Path(path)
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return None

    metrics: Dict[str, List[str]] = {}
    rows: List[TaskRow] = []
    for header, body in _tables(text):
        task_col = _column(header, "task")
        if task_col is not None:
            for cells in body:
                if len(cells) <= task_col:
                    continue
                record = {
                    name: (cells[index] if index < len(cells) else "")
                    for index, name in enumerate(header)
                }
                optimal = _first_int(record.get("optimal", ""))
                baseline = _first_int(record.get("baseline", ""))
                governed = _first_int(record.get("governed", ""))
                if optimal is None or baseline is None or governed is None:
                    continue
                rows.append(
                    TaskRow(
                        task=record.get("task", ""),
                        kind=record.get("kind", ""),
                        optimal=optimal,
                        baseline=baseline,
                        governed=governed,
                        rule=record.get("rule", ""),
                    )
                )
            continue
        # The metrics table has no header cell called "task"; its rows are
        # keyed by their first cell, which is prose.
        for cells in body:
            if cells:
                metrics[cells[0]] = cells[1:]

    def pick(prefix: str, column: int) -> Optional[str]:
        for key, values in metrics.items():
            if key.startswith(prefix):
                if column < len(values):
                    return values[column]
                return None
        return None

    baseline_calls = _first_int(pick("调用数", 0) or "")
    governed_calls = _first_int(pick("调用数", 1) or "")
    if baseline_calls is None or governed_calls is None:
        return None
    if not rows:
        return None

    return Report(
        baseline_calls=baseline_calls,
        governed_calls=governed_calls,
        saved_pct=_first_float(pick("省调用", 1) or ""),
        right_baseline=pick("停对了", 0) or "—",
        right_governed=pick("停对了", 1) or "—",
        early_governed=pick("停早了", 1) or "—",
        late_baseline=pick("停晚了", 0) or "—",
        acc_baseline=_first_float(pick("Accuracy@K", 0) or ""),
        acc_governed=_first_float(pick("Accuracy@K", 1) or ""),
        tasks=tuple(rows),
    )


# -- svg helpers ----------------------------------------------------------


def _f(value: float, digits: int = 1) -> str:
    return f"{value:.{digits}f}"


def _svg(width: int, height: int, body: str, label: str) -> str:
    # No ``height`` attribute: the width is fluid, so a fixed pixel height would
    # letterbox the drawing at narrow widths. ``style="height:auto"`` lets the
    # viewBox decide, which keeps the aspect ratio at any container size.
    return (
        f'<svg class="chart" viewBox="0 0 {width} {height}" width="100%" '
        f'style="height:auto" role="img" aria-label="{label}" '
        f'preserveAspectRatio="xMinYMin meet">{body}</svg>'
    )


def _text(x: float, y: float, value: str, *, size: float = 11, fill: str = "var(--muted)",
          anchor: str = "middle", weight: int = 400) -> str:
    return (
        f'<text x="{_f(x)}" y="{_f(y)}" font-size="{size}" fill="{fill}" '
        f'text-anchor="{anchor}" font-weight="{weight}">{value}</text>'
    )


# -- charts ---------------------------------------------------------------


def chart_task_steps(
    tasks: Sequence[TaskRow],
    *,
    width: int = 680,
    height: int = 250,
) -> str:
    """Three bars per task: hand-counted optimum, baseline, governed.

    Drawing the optimum next to both runs is the point. A chart of
    baseline-governed alone would show a saving; showing the optimum shows that
    the *governed* run lands on it, which is the claim under test.
    """
    if not tasks:
        return ""
    left, right, top, bottom = 34, 14, 20, 44
    plot_w = width - left - right
    plot_h = height - top - bottom

    ceiling = max(max(task.baseline for task in tasks), 1)
    ceiling += ceiling % 2  # even ticks: 11 -> 12
    slot = plot_w / len(tasks)
    bar = max(3.0, min(7.0, (slot - 7) / 3))
    gap = 1.2

    def y(value: float) -> float:
        return top + plot_h - (value / ceiling) * plot_h

    parts: List[str] = []
    for tick in (0, ceiling // 2, ceiling):
        parts.append(
            f'<line x1="{_f(left)}" y1="{_f(y(tick))}" x2="{_f(width - right)}" '
            f'y2="{_f(y(tick))}" stroke="var(--line)" stroke-width="1" '
            f'{"" if tick else ""}/>'
        )
        parts.append(_text(left - 7, y(tick) + 4, str(tick), anchor="end"))

    for index, task in enumerate(tasks):
        centre = left + slot * (index + 0.5)
        start = centre - (3 * bar + 2 * gap) / 2
        for offset, value, fill, opacity in (
            (0, task.optimal, "var(--muted)", "0.40"),
            (1, task.baseline, "var(--bad)", "0.72"),
            (2, task.governed, "var(--accent)", "0.92"),
        ):
            x = start + offset * (bar + gap)
            height_value = max(1.2, (value / ceiling) * plot_h)
            parts.append(
                f'<rect class="bar-grow" x="{_f(x)}" y="{_f(y(value))}" '
                f'width="{_f(bar)}" height="{_f(height_value)}" rx="1.6" '
                f'fill="{fill}" fill-opacity="{opacity}">'
                f"<title>{task.task} · {value}</title></rect>"
            )
        if index % 2 == 0:
            parts.append(
                _text(centre, height - bottom + 16, task.task, size=10)
            )

    legend_y = height - 10
    items = (
        ("最优（手数）", "var(--muted)", "0.40"),
        ("基线", "var(--bad)", "0.72"),
        ("网关", "var(--accent)", "0.92"),
    )
    x_cursor = left
    for label, fill, opacity in items:
        parts.append(
            f'<rect x="{_f(x_cursor)}" y="{_f(legend_y - 7)}" width="8" height="8" '
            f'rx="2" fill="{fill}" fill-opacity="{opacity}"/>'
        )
        parts.append(
            _text(x_cursor + 13, legend_y, label, size=11, anchor="start")
        )
        x_cursor += 24 + len(label) * 11
    return _svg(width, height, "".join(parts), "每个任务的最优、基线、网关步数")


def chart_calls(report: Report, *, width: int = 680) -> str:
    """Two horizontal bars. The one number the whole project is about."""
    height = 96
    left, right = 52, 120
    plot_w = width - left - right
    ceiling = max(report.baseline_calls, report.governed_calls, 1)

    rows = (
        ("基线", report.baseline_calls, "var(--bad)", "0.72"),
        ("网关", report.governed_calls, "var(--accent)", "0.92"),
    )
    parts: List[str] = []
    for index, (label, value, fill, opacity) in enumerate(rows):
        y = 20 + index * 40
        length = max(3.0, (value / ceiling) * plot_w)
        parts.append(_text(left - 10, y + 13, label, anchor="end", size=12, fill="var(--ink)"))
        parts.append(
            f'<rect class="bar-grow" x="{left}" y="{_f(y)}" width="{_f(length)}" '
            f'height="20" rx="6" fill="{fill}" fill-opacity="{opacity}">'
            f"<title>{label}: {value}</title></rect>"
        )
        parts.append(
            _text(left + length + 10, y + 15, f"{value}", anchor="start",
                  size=13, fill="var(--ink)", weight=600)
        )
    if report.saved_pct is not None:
        parts.append(
            _text(width - 14, height - 8, f"省 {_f(report.saved_pct)}%", anchor="end",
                  size=12, fill="var(--accent)", weight=600)
        )
    return _svg(width, height, "".join(parts), "基线与会话的调用数对比")


def chart_accuracy(report: Report, *, width: int = 680) -> str:
    """Accuracy@K as two dots on a 0.90-1.00 track.

    Zoomed on purpose: on a 0-1 axis both points sit at the top and the chart
    says nothing. The axis is labelled so the zoom is not a trick.
    """
    if report.acc_baseline is None or report.acc_governed is None:
        return ""
    low, high = 0.90, 1.00
    height = 88
    left, right = 52, 24
    plot_w = width - left - right

    def x(value: float) -> float:
        ratio = (value - low) / (high - low)
        return left + max(0.0, min(1.0, ratio)) * plot_w

    parts: List[str] = [
        f'<line x1="{left}" y1="46" x2="{width - right}" y2="46" '
        f'stroke="var(--line-strong)" stroke-width="1"/>'
    ]
    for tick in (0.90, 0.95, 1.00):
        parts.append(
            f'<line x1="{_f(x(tick))}" y1="42" x2="{_f(x(tick))}" y2="50" '
            f'stroke="var(--line-strong)" stroke-width="1"/>'
        )
        parts.append(_text(x(tick), 66, _f(tick, 2), size=10))
    for label, value, fill, above in (
        ("基线", report.acc_baseline, "var(--bad)", True),
        ("网关", report.acc_governed, "var(--accent)", False),
    ):
        cy = 28 if above else 64
        parts.append(
            f'<circle cx="{_f(x(value))}" cy="{cy}" r="5.5" fill="{fill}" fill-opacity="0.9"/>'
        )
        parts.append(
            _text(x(value), cy - 11 if above else cy + 17, f"{label} {_f(value, 2)}",
                  size=11, fill=fill, weight=600)
        )
    return _svg(width, height, "".join(parts), "Accuracy@K：基线与网关")
