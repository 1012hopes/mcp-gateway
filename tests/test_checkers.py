"""D12 acceptance: 40/40 checker self-test, plus the guards the fixtures cannot see.

Why a checker needs a test at all
---------------------------------
Twenty checkers, one bug, every number in the metric table wrong -- and nothing
raises. A checker that accepts everything reports 20/20 "correct stops"; one
that rejects everything reports a 100% misstop rate. Both look like findings.

So every task ships a pair: a `good` sample the checker must accept and a `bad`
one it must refuse *for the stated reason*. The `good` side is the governed
run's real delivery (generated by `scripts/make_fixtures.py`), which makes this
file a regression test for the frozen expectations too: if a checker's idea of
the answer drifts from what the database says, the good sample stops passing.

What the fixtures cannot see, and is tested here instead
-------------------------------------------------------
* an adversarial rephrasing that drops the subject token (the guard turns itself
  off silently);
* an empty answer to a *different* question (empty set is a subset of everything);
* a truncated re-read hiding a row that was delivered earlier (the overshoot tail
  re-asks with ``limit 1``).
"""

from __future__ import annotations

import json
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from agent.policy import FUTILE_SQL  # noqa: E402
from agent.tasks import load_tasks  # noqa: E402
from tasks.checkers import CHECKERS, Answer, check, known_ids  # noqa: E402
from tasks.checkers.adversarial import SUBJECTS  # noqa: E402
from tasks.checkers.core import facts, project, touched  # noqa: E402

FIXTURES = ROOT / "tests" / "fixtures"
TASKS = load_tasks()
BY_ID = {task.id: task for task in TASKS}


def _load(kind: str, task_id: str) -> dict:
    return json.loads((FIXTURES / kind / f"{task_id}.json").read_text(encoding="utf-8"))


def _answers(body: dict) -> list:
    return [Answer.from_dict(item) for item in body["answers"]]


class CoverageTests(unittest.TestCase):
    def test_every_task_has_a_checker(self):
        self.assertEqual(known_ids(), sorted(BY_ID))

    def test_no_checker_for_a_task_that_does_not_exist(self):
        # An orphan checker is a task that was deleted and a metric that still
        # counts it -- the table would keep twenty rows while the set had 19.
        self.assertEqual(sorted(set(CHECKERS) - set(BY_ID)), [])

    def test_every_task_has_both_fixtures(self):
        for task_id in BY_ID:
            with self.subTest(task=task_id):
                for kind in ("good", "bad"):
                    path = FIXTURES / kind / f"{task_id}.json"
                    self.assertTrue(path.exists(), f"missing {path}")
                    self.assertEqual(_load(kind, task_id)["task"], task_id)

    def test_an_unknown_task_is_an_error_not_a_pass(self):
        with self.assertRaises(KeyError):
            check("t99", [])


class FixtureTests(unittest.TestCase):
    def test_all_forty_samples_behave(self):
        accepted, refused = [], []
        for task_id in sorted(BY_ID):
            with self.subTest(task=task_id, kind="good"):
                verdict = check(task_id, _answers(_load("good", task_id)))
                self.assertTrue(verdict.ok, verdict.detail)
                accepted.append(task_id)
            with self.subTest(task=task_id, kind="bad"):
                verdict = check(task_id, _answers(_load("bad", task_id)))
                self.assertFalse(verdict.ok, "the bad sample was accepted")
                refused.append(task_id)
        self.assertEqual(len(accepted) + len(refused), 40)

    def test_every_refusal_names_the_reason_it_was_built_for(self):
        for task_id in sorted(BY_ID):
            with self.subTest(task=task_id):
                body = _load("bad", task_id)
                verdict = check(task_id, _answers(body))
                self.assertIn(
                    body["expect"].lower(),
                    verdict.detail.lower(),
                    f"refused for another reason: {verdict.detail}",
                )

    def test_the_bad_sample_is_not_simply_empty(self):
        # "It rejected because there was nothing there" would make the pair
        # worthless: the interesting failure is an answer that looks complete.
        for task_id in sorted(BY_ID):
            with self.subTest(task=task_id):
                good = _load("good", task_id)["answers"]
                bad = _load("bad", task_id)["answers"]
                self.assertEqual(len(good), len(bad), "the mutation changed the call count")
                good_rows = sum(len(a.get("payload", {}).get("rows") or []) for a in good)
                bad_rows = sum(len(a.get("payload", {}).get("rows") or []) for a in bad)
                self.assertGreaterEqual(bad_rows, good_rows - 1)
                self.assertGreaterEqual(bad_rows, 1)


class AdversarialSubjectTests(unittest.TestCase):
    def test_every_rephrasing_names_the_subject(self):
        for task_id in sorted(SUBJECTS):
            task = BY_ID[task_id]
            tokens = SUBJECTS[task_id][2]
            # t02 predates the per-task ``futile_sql`` field: its rephrasings are
            # still the policy's default table, and the guard has to hold for
            # whichever list the policy will actually use.
            sqls = task.futile_sql or FUTILE_SQL
            with self.subTest(task=task_id):
                self.assertTrue(sqls, "no rephrasings to check")
                for sql in sqls:
                    self.assertTrue(
                        any(token in sql.lower() for token in tokens),
                        f"{sql!r} names none of {tokens}",
                    )

    def test_the_subject_lives_in_the_table_the_checker_reads(self):
        for task_id, (table, _, _) in sorted(SUBJECTS.items()):
            with self.subTest(task=task_id):
                for sql in BY_ID[task_id].futile_sql or FUTILE_SQL:
                    self.assertIn(table, sql.lower())

    def test_an_empty_answer_to_another_question_is_not_an_answer(self):
        # Same table, same shape, empty rows -- and no bearing on the question.
        answers = [
            Answer("sqlite.query", {"sql": "select label from labels where incident_id = 99"}, {"rows": []})
        ]
        verdict = check("t16", answers)
        self.assertFalse(verdict.ok)
        self.assertIn("never asked", verdict.detail)

    def test_never_asking_is_not_an_answer(self):
        answers = [Answer("sqlite.list_tables", {}, {"tables": ["labels"]})]
        for task_id in sorted(SUBJECTS):
            with self.subTest(task=task_id):
                self.assertFalse(check(task_id, answers).ok)


class CoreTests(unittest.TestCase):
    def test_a_truncated_reread_does_not_hide_a_delivered_row(self):
        # The overshoot tail re-asks the same question with ``limit 1``: a
        # checker reading only the last answer would grade the re-read.
        answers = [
            Answer("sqlite.query", {"sql": "select name, stars from repos"},
                   {"rows": [{"name": "a", "stars": 2}, {"name": "b", "stars": 1}]}),
            Answer("sqlite.query", {"sql": "select name, stars from repos", "limit": 1},
                   {"rows": [{"name": "a", "stars": 2}]}),
        ]
        self.assertEqual(
            sorted(r["name"] for r in facts(answers, "repos")), ["a", "b"]
        )

    def test_rows_are_only_read_from_queries_about_that_table(self):
        answers = [
            Answer("sqlite.query", {"sql": "select name from repos"}, {"rows": [{"name": "a"}]}),
            Answer("sqlite.query", {"sql": "select label from labels"}, {"rows": [{"label": "x"}]}),
        ]
        self.assertEqual(facts(answers, "repos"), [{"name": "a"}])
        self.assertEqual(touched(answers, "repos"), 1)
        self.assertEqual(facts(answers, "incidents"), [])

    def test_a_row_missing_a_required_column_is_dropped_not_padded(self):
        answers = [
            Answer("sqlite.query", {"sql": "select name, stars from repos"},
                   {"rows": [{"name": "a", "stars": 2}, {"name": "b"}]}),
        ]
        self.assertEqual(project(facts(answers, "repos"), ("name", "stars")), {("a", 2)})

    def test_an_errored_query_is_not_a_row_set(self):
        answers = [Answer("sqlite.query", {"sql": "select * from labels"}, {"error": "boom"})]
        self.assertEqual(facts(answers, "labels"), [])
        self.assertEqual(touched(answers, "labels"), 0)


if __name__ == "__main__":  # pragma: no cover
    unittest.main()
